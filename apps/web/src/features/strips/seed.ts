/**
 * Airports outside the demo set (opened by ICAO from a live session)
 * get an empty AWOS shell — the protocol carries no weather, so the
 * panel shows placeholders instead of invented numbers.
 */
function placeholderMetar(icao: string): Metar {
  return {
    station: icao,
    obsTime: '',
    raw: '',
    wind: '',
    windNote: '',
    qnh: '—',
    qnhAlt: '',
    temp: '—',
    hum: '',
    vis: '—',
    visUnit: '',
    ceil: '—',
    ceilUnit: '',
    visM: 10000,
    ceilFt: 99999,
    rwys: [],
    atis: '—',
    depFreq: '',
    clrNote: '',
  };
}

export function makeTab(icao: string): StripsTab {
  const metar = METARS[icao] ?? placeholderMetar(icao);
  const seeds = STRIP_SEEDS[icao] ?? [];
  return {
    icao,
    metar,
    strips: seeds.map(makeStrip),
    bays: defaultBays(),
    locks: {},
    feed: [],
    archived: [],
    unseen: 0,
  };
}

export function initialStripsState(): StripsState {
  return {
    tabs: { LPPT: makeTab('LPPT'), LPPR: makeTab('LPPR') },
    tabsOrder: ['LPPT', 'LPPR'],
    activeTab: 'LPPT',
    toasts: [],
    seq: 100,
    feedOn: true,
    controllers: [],
    seenAirports: [],
  };
}
