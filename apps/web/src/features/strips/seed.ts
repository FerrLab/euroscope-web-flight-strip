type StripSeed = Pick<
  Strip,
  | 'id'
  | 'cs'
  | 'airline'
  | 'type'
  | 'wake'
  | 'adep'
  | 'ades'
  | 'gate'
  | 'sqkA'
  | 'proc'
  | 'procKind'
  | 'rwy'
  | 'cfl'
  | 'dir'
  | 'bay'
> &
  Partial<Strip>;

export function makeStrip(seed: StripSeed): Strip {
  return {
    sqkS: '',
    cleared: false,
    dcl: 'NONE',
    freeText: '',
    suggest: null,
    anim: false,
    xfr: null,
    fpl: null,
    ...seed,
  };
}

